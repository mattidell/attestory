"""Core v108 from published v107: the four code B wash-sale explanations name the correct basis.

Run: python3 build.py <new-directory-outside-repository> [--publish]

The method is sale-explanation-wording Track 1 (its build.py, whose literal
replacement and pin search this script imports). Each citizen in wording.json
gets a v3 successor whose only differences are the declared sentence and its
root version; undoing exactly those recovers every predecessor byte. The
closure over {"id", "version"} pins is checked to have one level (nothing
pins an explanation). tools.package_successor generates and validates
package v108, registry v106 and release v106 in the scratch directory.
--publish then copies the four successors and the three generated files into
packages/, refusing to overwrite anything; the committed bytes are the
generated bytes.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[4]
sys.path.insert(0, str(REPO))
from tools.package_successor import SuccessorError, generate_to_directory  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "sew_build", HERE.parent / "sale-explanation-wording-evidence" / "build.py")
assert _spec is not None and _spec.loader is not None
sew = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sew)

STEM = "demo.release.sli-worksheet-integration.2025"
FROM = {"core": "v107", "registry": "v105", "release": "v105"}
TO = {"core": "v108", "registry": "v106", "release": "v106"}
SOURCE = REPO / "packages/content/tax/2025"
RELEASES = REPO / "packages/sample_data/student_loan_worksheet_integration/publication_surface/releases"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("scratch")
    parser.add_argument("--publish", action="store_true")
    args = parser.parse_args()
    scratch = Path(args.scratch).resolve()
    assert REPO not in scratch.parents and not scratch.exists()
    content, rel = scratch / "content", scratch / "releases"
    shutil.copytree(SOURCE, content)
    shutil.copytree(RELEASES, rel)
    manifest = json.loads((HERE / "wording.json").read_text(encoding="utf-8"))["replacements"]
    package = json.loads((SOURCE / f"package.core-calculations.{FROM['core']}.json").read_text(encoding="utf-8"))
    pins = {m["id"]: m for m in package["members"]}
    changed = {r["id"] for r in manifest}
    targets = {(i, pins[i]["version"]) for i in changed}
    bodies = {}
    for path in SOURCE.glob("*.json"):
        body = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(body, dict) and "id" in body and "version" in body:
            bodies[(body["id"], body["version"])] = body
    pinning = []
    for member in package["members"]:
        body = bodies.get((member["id"], member["version"]))
        if member["id"] in changed or body is None:
            continue
        found: list = []
        for key, value in body.items():
            if key != "id":
                sew.pinned(value, targets, found)
        if found:
            pinning.append(member["id"])
    assert pinning == [], pinning
    members, entries, successors, written = [], [], [], []
    for row in manifest:
        cid = row["id"]
        old_version = pins[cid]["version"]
        assert old_version == row["version"], cid
        new_version = "v" + str(int(old_version[1:]) + 1)
        old_path = REPO / row["file"]
        raw = old_raw = old_path.read_text(encoding="utf-8")
        raw = sew.literal_replace(raw, row["old"], row["new"])
        raw, count = re.subn(r'(?m)^(  "version": ")' + re.escape(old_version) + r'("[,]?)$',
                             lambda m: m[1] + new_version + m[2], raw)
        assert count == 1, cid
        back = re.sub(r'(?m)^(  "version": ")' + re.escape(new_version) + r'("[,]?)$',
                      lambda m: m[1] + old_version + m[2], raw)
        back = sew.literal_replace(back, row["new"], row["old"])
        assert back == old_raw, cid
        next_name = re.sub(r"\.v\d+\.json$", f".{new_version}.json", old_path.name)
        assert not (content / next_name).exists() and not (SOURCE / next_name).exists(), next_name
        (content / next_name).write_text(raw, encoding="utf-8")
        written.append(next_name)
        members.append({"op": "replace", "old": pins[cid], "new": {**pins[cid], "version": new_version}})
        if any(e == {"id": cid, "version": old_version} for e in package["entrypoints"]):
            entries.append({"op": "replace", "old": {"id": cid, "version": old_version},
                            "new": {"id": cid, "version": new_version}})
        successors.append({"id": cid, "schema": pins[cid].get("schema"), "old_version": old_version,
                           "new_version": new_version, "predecessor": row["file"],
                           "successor_filename": next_name, "changed_properties": [row["property"]],
                           "successor_sha256": hashlib.sha256(raw.encode()).hexdigest(), "byte_undo_proof": True})
    changes = {"package_version": TO["core"], "release_version": TO["release"], "members": members,
               "entrypoints": entries}
    (scratch / "changes.json").write_text(json.dumps(changes, indent=2) + "\n")
    output = {"from": FROM, "to": TO, "wording_citizens": len(manifest), "cascade_levels": [len(manifest)],
              "citizens": len(successors), "member_replacements": len(members), "entrypoint_replacements": len(entries),
              "successors": successors}
    try:
        report = generate_to_directory(content / f"package.core-calculations.{FROM['core']}.json",
                                       content / f"published-packages.{FROM['registry']}.json",
                                       rel / f"{STEM}.{FROM['release']}.json",
                                       content, scratch / "changes.json", scratch / "generated")
    except SuccessorError as exc:
        output.update({"status": "rejected",
                       "failure": re.sub(r"/(?:Users|private|tmp|var)/\S+", "<path>", str(exc))[:2000]})
        (HERE / "build.json").write_text(json.dumps(output, indent=2) + "\n")
        raise SystemExit(output["failure"])
    generated = {"package.json": SOURCE / f"package.core-calculations.{TO['core']}.json",
                 "registry.json": SOURCE / f"published-packages.{TO['registry']}.json",
                 "release.json": RELEASES / f"{STEM}.{TO['release']}.json"}
    output.update({"status": "valid", "validation": "generate_to_directory passed package, registry and release validation",
                   "generated_sha256": {dst.name: hashlib.sha256((scratch / "generated" / src).read_bytes()).hexdigest()
                                        for src, dst in generated.items()},
                   "generation": {k: v for k, v in report.items() if isinstance(v, (str, int, bool))}
                   if isinstance(report, dict) else str(report)})
    if args.publish:
        for name in written:
            assert not (SOURCE / name).exists(), name
            shutil.copyfile(content / name, SOURCE / name)
        for src, dst in generated.items():
            assert not dst.exists(), dst.name
            shutil.copyfile(scratch / "generated" / src, dst)
        output["published"] = sorted(written) + sorted(dst.name for dst in generated.values())
    (HERE / "build.json").write_text(json.dumps(output, indent=2) + "\n")
    print(json.dumps({k: v for k, v in output.items() if k != "successors"}, indent=2))


if __name__ == "__main__":
    main()
